"""Create a dedicated server-local figure workspace without inventing data."""
import argparse
import json
from pathlib import Path
import yaml


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--execute", action="store_true")
    args = parser.parse_args()
    root = args.output_dir.resolve()
    template = Path(__file__).resolve().parents[1] / "configs/paper_results_figures.full.example.yaml"
    recipe = yaml.safe_load(template.read_text())
    inputs = set()
    # Plot tables live in this workspace; other analysis outputs (for example
    # clinical_scores/headline_scores.csv) stay where their own step writes them,
    # one level up in the analysis root.
    for plate in recipe["figures"]:
        for section in ("tables", "json_inputs"):
            for key, source in plate.get(section, {}).items():
                if source.startswith("${OPERA_PAPER_ANALYSIS_ROOT}/"):
                    path = root.parent / source.split("}/", 1)[1]
                else:
                    path = root / "plot_tables" / Path(source).name
                plate[section][key] = str(path)
                inputs.add(str(path))
    table_template = template.parent / "supplement_tables.example.yaml"
    table_recipe = yaml.safe_load(table_template.read_text())
    for spec in table_recipe["tables"]:
        spec["source"] = str(root / "plot_tables" / Path(spec["source"]).name)
        inputs.add(spec["source"])
    print(json.dumps({"workspace": str(root), "recipe": str(root / "figures.yaml"),
                      "required_inputs": sorted(inputs)}, indent=2))
    if not args.execute:
        return
    for child in ("plot_tables", "embedding_exports"):
        (root / child).mkdir(parents=True, exist_ok=True)
    config = root / "figures.yaml"
    if config.exists():
        raise FileExistsError("Keep the existing reviewed recipe; use a new workspace to initialise again")
    config.write_text(yaml.safe_dump(recipe, sort_keys=False, allow_unicode=True))
    (root / "supplement_tables.yaml").write_text(yaml.safe_dump(table_recipe, sort_keys=False))
    (root / "required_inputs.json").write_text(json.dumps(sorted(inputs), indent=2))
    (root / "README.md").write_text(
        "# Real figure inputs\n\nPopulate required_inputs.json from audited analysis outputs. "
        "No data are generated by initialisation. Review clinical example endpoint, "
        "cutoffs and operating threshold before rendering. Embedding exports go in "
        "embedding_exports; projected coordinates go in plot_tables.\n"
    )


if __name__ == "__main__":
    main()
